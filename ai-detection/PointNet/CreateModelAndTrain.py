import os
import json
import torch
from torch.utils.data import Dataset, DataLoader, random_split
import open3d as o3d
import numpy as np

class PointCloudDataset(Dataset):
    def __init__(self, pcd_dir, json_dir):
        self.pcd_paths = []
        self.label_paths = []
        for fname in sorted(os.listdir(pcd_dir)):
            if fname.endswith(".pcd"):
                frame_name = os.path.splitext(fname)[0]
                self.pcd_paths.append(os.path.join(pcd_dir, fname))
                self.label_paths.append(os.path.join(json_dir, frame_name + ".json"))

    def __len__(self):
        return len(self.pcd_paths)

    def __getitem__(self, idx):
        # Pointcloud laden
        pcd = o3d.io.read_point_cloud(self.pcd_paths[idx])
        points = np.asarray(pcd.points)

        # Labels laden
        with open(self.label_paths[idx], "r") as f:
            data = json.load(f)

        labels = np.zeros(points.shape[0], dtype=np.int64)
        for figure in data.get("figures", []):
            if figure["geometryType"] == "point_cloud":
                indices = figure["geometry"]["indices"]
                labels[indices] = 1  # Mensch = 1, Hintergrund = 0

        return torch.from_numpy(points).float(), torch.from_numpy(labels).long()

