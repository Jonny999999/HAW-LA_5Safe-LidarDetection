import os
import json
import numpy as np
import open3d as o3d

def load_frame(pcd_path, json_path):
    # PCD laden
    pcd = o3d.io.read_point_cloud(pcd_path)
    points = np.asarray(pcd.points)

    # JSON laden
    with open(json_path, 'r') as f:
        data = json.load(f)

    # Leeres Label-Array initialisieren
    labels = np.array(['unlabeled'] * len(points), dtype=object)

    # Mapping: indices -> label
    for figure in data.get("figures", []):
        indices = figure["geometry"]["indices"]
        label = figure.get("geometryType", "unlabeled")
        # Falls du lieber den Klassentitel willst:
        # label = figure.get("classTitle", "unlabeled")
        labels[indices] = label

    return points, labels

def load_dataset(dataset_dir):
    pcd_dir = os.path.join(dataset_dir, "pcd")
    json_dir = os.path.join(dataset_dir, "json")

    frames = []
    pcd_files = sorted([f for f in os.listdir(pcd_dir) if f.endswith(".pcd")])

    for pcd_file in pcd_files:
        name = os.path.splitext(pcd_file)[0]
        pcd_path = os.path.join(pcd_dir, pcd_file)
        json_path = os.path.join(json_dir, f"{name}.json")

        points, labels = load_frame(pcd_path, json_path)

        frame = {
            "name": name,
            "points": points,
            "labels": labels
        }
        frames.append(frame)

    return frames

