# 2. DataLoader mit collate_fn zum Padding

from torch.utils.data import DataLoader

def collate_fn(batch):
    points_list = [item[0] for item in batch]
    labels_list = [item[1] for item in batch]

    max_points = max(p.shape[0] for p in points_list)
    batch_size = len(batch)

    padded_points = torch.zeros((batch_size, max_points, 3), dtype=torch.float32)
    padded_labels = torch.zeros((batch_size, max_points), dtype=torch.long)

    for i, (points, labels) in enumerate(zip(points_list, labels_list)):
        length = points.shape[0]
        padded_points[i, :length, :] = points
        padded_labels[i, :length] = labels

    return padded_points, padded_labels

train_loader = DataLoader(train_dataset, batch_size=4, shuffle=True, collate_fn=collate_fn)
val_loader = DataLoader(val_dataset, batch_size=4, collate_fn=collate_fn)

# 3. Modell: Einfaches PointNet Light

import torch.nn as nn
import torch.nn.functional as F

class SimplePointNet(nn.Module):
    def __init__(self, num_classes=2):
        super(SimplePointNet, self).__init__()
        self.fc1 = nn.Linear(3, 64)
        self.fc2 = nn.Linear(64, 128)
        self.fc3 = nn.Linear(128, 256)
        self.fc4 = nn.Linear(256, 128)
        self.fc5 = nn.Linear(128, num_classes)

    def forward(self, x):
        # x: [B, N, 3]
        x = F.relu(self.fc1(x))
        x = F.relu(self.fc2(x))
        x = F.relu(self.fc3(x))
        x = F.relu(self.fc4(x))
        x = self.fc5(x)  # Output: [B, N, num_classes]
        return x

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = SimplePointNet().to(device)

# 4. Training & Validation Loop

import torch.optim as optim

criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

def train_epoch(loader):
    model.train()
    total_loss = 0
    for points, labels in loader:
        points = points.to(device)
        labels = labels.to(device)
        optimizer.zero_grad()
        outputs = model(points)             # [B, N, 2]
        outputs = outputs.permute(0, 2, 1) # [B, 2, N] für CrossEntropyLoss
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()
        total_loss += loss.item()
    return total_loss / len(loader)

def validate(loader):
    model.eval()
    total_loss = 0
    with torch.no_grad():
        for points, labels in loader:
            points = points.to(device)
            labels = labels.to(device)
            outputs = model(points)
            outputs = outputs.permute(0, 2, 1)
            loss = criterion(outputs, labels)
            total_loss += loss.item()
    return total_loss / len(loader)

num_epochs = 20
for epoch in range(num_epochs):
    train_loss = train_epoch(train_loader)
    val_loss = validate(val_loader)
    print(f"Epoch {epoch+1}/{num_epochs} - Train Loss: {train_loss:.4f} - Val Loss: {val_loss:.4f}")

