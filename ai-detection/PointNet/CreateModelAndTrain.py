from sklearn.cluster import DBSCAN
import numpy as np

def cluster_and_count_people(points, preds, eps=0.5, min_samples=10):
    """
    Clustert die Punkte, die als Mensch klassifiziert wurden.
    Args:
        points: np.array (N,3) Punktkoordinaten
        preds: np.array (N,) Vorhersagen 0/1
        eps: float, max. Distanz für DBSCAN (anpassen je nach Daten)
        min_samples: int, Mindestpunkte pro Cluster

    Returns:
        cluster_labels: np.array mit Cluster-IDs für Menschen-Punkte (-1 = Rauschen)
        num_people: int, Anzahl gefundener Cluster (ohne Rauschen)
    """
    human_points = points[preds == 1]
    if len(human_points) == 0:
        return np.array([]), 0

    clustering = DBSCAN(eps=eps, min_samples=min_samples).fit(human_points)
    cluster_labels = clustering.labels_
    num_people = len(set(cluster_labels)) - (1 if -1 in cluster_labels else 0)
    return cluster_labels, num_people

